package com.packstudio.build;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.packstudio.compat.MinecraftCompat;
import com.packstudio.compat.MinecraftCompatProvider;
import java.io.InputStream;
import java.util.List;
import java.util.Properties;
import net.fabricmc.loader.api.FabricLoader;
import net.minecraft.SharedConstants;
import org.junit.jupiter.api.Test;

/**
 * Verifies that this build really targets the Minecraft version recorded in its own build identity.
 *
 * <p>{@code packstudio-build.properties} is generated by Gradle for the selected
 * {@code -Pminecraft_version} and packaged into the jar. Running this test while the classpath resolves a
 * different Minecraft version therefore fails, which is what stops a release from being published for a
 * version whose build did not target it.
 */
class TargetIdentityTest {

    private static Properties buildIdentity() throws Exception {
        try (InputStream in = TargetIdentityTest.class.getClassLoader()
                .getResourceAsStream("packstudio-build.properties")) {
            assertNotNull(in, "packstudio-build.properties missing from the jar");
            Properties properties = new Properties();
            properties.load(in);
            return properties;
        }
    }

    @Test
    void classpathMinecraftMatchesDeclaredTarget() throws Exception {
        Properties identity = buildIdentity();
        String declaredVersion = identity.getProperty("minecraft_version");
        String declaredFamily = identity.getProperty("minecraft_family");
        String resolvedVersion = SharedConstants.getCurrentVersion().name();

        assertEquals(declaredVersion, resolvedVersion,
                "sources were compiled against Minecraft " + resolvedVersion
                        + " but this target declares " + declaredVersion);
        assertTrue(List.of("26.1", "26.2", "26.3").contains(declaredFamily),
                "unexpected API family: " + declaredFamily);
    }

    @Test
    void declaredFabricVersionsAreTheOfficialOnesForThisTarget() throws Exception {
        Properties identity = buildIdentity();
        String version = identity.getProperty("minecraft_version");
        String fabricApi = identity.getProperty("fabric_api_version");

        String expectedApi = switch (version) {
            case "26.1", "26.1.1", "26.1.2" -> "0.155.3+26.1.2";
            case "26.2" -> "0.161.0+26.2";
            case "26.3" -> "0.165.2+26.3";
            default -> throw new AssertionError("untracked Minecraft target " + version);
        };
        assertEquals(expectedApi, fabricApi, "Fabric API version for " + version);
        assertEquals("0.20.1", identity.getProperty("fabric_loader_version"), "Fabric Loader version");
        assertEquals("1.0.0", identity.getProperty("mod_version"), "mod version");
    }

    @Test
    void exactlyOneCompatibilityLayerIsPresentAndLoads() {
        assertNotNull(MinecraftCompatProvider.get(), "compatibility provider returned no implementation");
        assertTrue(MinecraftCompat.class.isAssignableFrom(MinecraftCompatProvider.get().getClass()));
    }

    @Test
    void sharedCodeLoadsAgainstThisMinecraftVersion() throws Exception {
        for (String className : List.of(
                "net.minecraft.server.packs.repository.PackRepository",
                "net.minecraft.client.gui.GuiGraphicsExtractor",
                "net.minecraft.client.gui.screens.Screen",
                "net.minecraft.client.KeyMapping",
                "com.packstudio.client.screen.PackStudioScreen",
                "com.packstudio.manager.PackRepositoryManager",
                "com.packstudio.compatibility.PackMetadataInspector",
                "com.packstudio.manager.PackIconCache",
                "com.packstudio.core.PackStudioConstants"
        )) {
            Class.forName(className);
        }

        // Family-specific types: present only where the API family provides them.
        String family = buildIdentity().getProperty("minecraft_family");
        ClassNotFoundException missingMetadataResources = null;
        try {
            Class.forName("net.minecraft.server.packs.PackMetadataResources");
        } catch (ClassNotFoundException e) {
            missingMetadataResources = e;
        }
        if ("26.3".equals(family)) {
            assertNull(missingMetadataResources,
                    "PackMetadataResources must exist on the 26.3 family");
        } else {
            assertTrue(missingMetadataResources != null,
                    "PackMetadataResources must not exist before the 26.3 API family");
        }
    }

    @Test
    void modMetadataReportsTheTargetedMinecraftVersion() {
        String modVersion = FabricLoader.getInstance()
                .getModContainer("packstudio")
                .orElseThrow(() -> new AssertionError("packstudio mod container unavailable"))
                .getMetadata()
                .getVersion()
                .getFriendlyString();
        assertEquals("1.0.0+mc" + SharedConstants.getCurrentVersion().name(), modVersion,
                "fabric.mod.json version must name the Minecraft version this jar targets");
    }
}
